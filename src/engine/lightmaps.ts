// Baked indirect-light atlases (Cycles), one per floor category — written by `blender/build_nakhla.py --bake=<floor>:<category>`.
// R = sky light, G = lamp light, B = sunlight after its first bounce (baked for a 15:00 summer sun), sqrt-encoded luminance.
// Each atlas is normalised by its own 99.5th-percentile reference (skyRef / lampRef / sunRef in public/lightmaps/<cat>.json).
// The residential gains were calibrated against the Cycles stills by measurement (GOLDEN_APARTMENT_REVIEW.md §3); every
// other floor is scaled from them by the ratio of its reference to the residential one, so all floors share ONE physical
// scale instead of being tuned by eye. A floor without modelled fittings gets (correctly) almost no lamp light.
export interface LightmapMeta { file: string; floor?: string; skyGain: number; lampGain: number; sunGain: number }

const CAL = { skyGain: 6.2, lampGain: 2.0, sunGain: 4.6 };                                   // calibrated: residential
const RES_REF = { sky: 0.4685334265232086, lamp: 1.4674714803695679, sun: 1.4568992853164673 };
// V11.5: under PBR Neutral (no highlight roll-off, unlike AgX) the big glazed amenity floors (dining 2.1×, wellness 2.7× the
// residential sky / sun reference) clipped to peach-white. Their sky and sun gains are compressed toward the calibrated
// residential level (ratio^0.35); lamp light keeps its physical ratio.
const k = (r: number) => Math.pow(r, 0.35);
const scaled = (file: string, sky: number, lamp: number, sun: number): LightmapMeta => ({
  file: `${file}.png`, floor: `${file}_floor.png`,
  skyGain: CAL.skyGain * k(sky / RES_REF.sky), lampGain: CAL.lampGain * (lamp / RES_REF.lamp), sunGain: CAL.sunGain * k(sun / RES_REF.sun),
});

export const LIGHTMAPS: Record<string, LightmapMeta> = {
  // GENERATED by tools/update_lightmaps.py from public/lightmaps/*.json
  residential: scaled('residential', 0.38510188460350037, 2.569706678390503, 1.3411061763763428),
  ground: scaled('ground', 0.3272119462490082, 0.2919771373271942, 1.1935089826583862),
  wellness: scaled('wellness', 1.3437122106552124, 0.5503767132759094, 3.8811495304107666),
  dining: scaled('dining', 0.8313199877738953, 0.4248172640800476, 3.0747106075286865),
};
