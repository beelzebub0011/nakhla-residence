import { describe, expect, it } from 'vitest';
import { mkdirSync, writeFileSync } from 'node:fs';
import { SCENES, SCENE_BY_ID, UNUSED_VIEWS, placeForScene, sceneForPlace } from '../../src/visual/catalog';
import { getFloorPlan } from '../../src/domain/plans';
import { FLOORS, UNIT_BY_ID } from '../../src/domain/tower';

// V11.2 §27/§29: every photo scene maps to a real place in the 3D model and back; places without a rendered view
// fall back to an honest parent. Also writes reports/SCENE_MAPPING.md (the scene ↔ 3D mapping document).

describe('photoreal scene catalogue', () => {
  it('uses every camera bookmark and only real 3D places', () => {
    expect(UNUSED_VIEWS).toEqual([]);
    for (const s of SCENES) if (s.roomKey) expect(getFloorPlan(s.floorId!).rooms.some((r) => r.key === s.roomKey), s.id).toBe(true);
  });
  it('round-trips: photo → 3D → photo lands on the same place', () => {
    for (const s of SCENES) {
      const p = placeForScene(s.id, { floorId: null, unitId: null });
      const back = sceneForPlace({ floorId: p.floorId, unitId: p.unitId, roomKey: p.roomKey, view: p.view, timeMinutes: p.timeMinutes });
      // exterior scenes all open the whole-tower view; the store remembers which one the visitor came from (store.chooseExperience)
      if (s.roomKey) expect(SCENE_BY_ID[back.sceneId].group, s.id).toBe(s.group); else expect(SCENE_BY_ID[back.sceneId].roomKey, s.id).toBeNull();
      if (p.unitId) expect(UNIT_BY_ID[p.unitId].floorId).toBe(p.floorId);
    }
  });
  it('keeps the visitor’s own apartment when the plan type matches', () => {
    expect(placeForScene('B_master', { floorId: 'F07', unitId: 'U07B' })).toMatchObject({ unitId: 'U07B', floorId: 'F07', note: 'same_type_other_floor' });
    expect(placeForScene('B_master', { floorId: 'F07', unitId: 'U07A' })).toMatchObject({ unitId: 'U04B', note: null });
  });
  it('every apartment room has a scene or an honest parent; writes the mapping document', () => {
    const rows: string[] = ['| 3D place | Photo scene | Exact? | Reason |', '|---|---|---|---|'];
    for (const f of FLOORS.filter((x) => ['F04', 'G', 'F10', 'F11'].includes(x.id))) {
      for (const r of getFloorPlan(f.id).rooms) {
        const unitId = r.key.startsWith('A.') ? `U04A` : r.key.startsWith('B.') ? 'U04B' : null;
        const m = sceneForPlace({ floorId: f.id, unitId, roomKey: r.key, view: 'room', timeMinutes: 960 });
        expect(SCENE_BY_ID[m.sceneId], r.key).toBeDefined();
        rows.push(`| ${f.id} · ${r.key} | ${m.sceneId} | ${m.exact ? 'yes' : 'no'} | ${m.reason} |`);
      }
    }
    const scenes = ['| Scene | Chapter | Group | Variant | 3D target (section · floor · unit · room) | Area m² |', '|---|---|---|---|---|---|',
      ...SCENES.map((s) => { const p = placeForScene(s.id, { floorId: null, unitId: null }); return `| ${s.id} | ${s.chapter} | ${s.group} | ${s.variant} | ${p.section} · ${p.floorId ?? '—'} · ${p.unitId ?? '—'} · ${p.roomKey ?? 'tower'} | ${s.areaSqm ?? '—'} |`; })];
    mkdirSync('reports', { recursive: true });
    writeFileSync('reports/SCENE_MAPPING.md', `# Scene mapping — photoreal website ↔ 3D model (generated by tests/unit/catalog.test.ts)\n\nRoutes: \`#/<lang>/visual/<sceneId>\` (photo site, \`home\` = overview) · \`#/<lang>/<explore|tour|design|amenities>?f=&u=&r=&v=\` (3D).\nShared state: locale, sound (muted by default), time of day, floor, unit, room. Scenes come from the same camera list as the Cycles renders (\`src/domain/views.ts\`).\n\n## ${SCENES.length} photo scenes → 3D\n\n${scenes.join('\n')}\n\n## 3D places → photo scene (rendered floors; residential floors 01–09 share the F04 plan)\n\n${rows.join('\n')}\n`, 'utf8');
  });
});
