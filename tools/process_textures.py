"""Prepare the CC0 Poly Haven PBR sets for the web build (no network access).
assets_src/polyhaven/*  ->  public/textures/<set>_{d,n,r}.jpg  +  src/engine/photosets.ts
'tint' sets are turned into neutral luminance maps (linear mean 0.6) so ONE scan can be recoloured
by the material colour (fabrics, linen, velvet, plaster) while keeping its real weave and relief."""
import os, sys, json
import numpy as np
from PIL import Image

SRC, OUT = 'assets_src/polyhaven', 'public/textures'
# name: (albedo file stem, real size in metres [w,h], tintable, licence author)
SETS = {
    'laminate_floor_02': ('diff', [1.7, 1.7], False, 'Dario Barresi, Charlotte Baglioni'),
    'oak_veneer_01': ('diff', [1.83, 1.83], False, 'Jenelle van Heerden'),
    'walnut_veneer': ('diff', [1.8, 1.8], False, 'Jenelle van Heerden'),
    'smoked_walnut_veneer': ('diff', [1.0, 1.0], False, 'Jenelle van Heerden'),
    'marble_01': ('diff', [1.5, 1.5], False, 'Rob Tuytel'),
    'wool_boucle': ('diff', [0.315, 0.39], False, 'colormass, Rico Cilliers'),
    'rough_linen': ('diff', [0.271, 0.271], True, 'colormass, Rico Cilliers'),
    'velour_velvet': ('diff', [0.284, 0.2735], True, 'colormass, Rico Cilliers'),
    'brown_leather': ('albedo', [0.4, 0.4], False, 'Rob Tuytel'),
    'white_plaster_02': ('diff', [1.0, 1.0], True, 'Rob Tuytel'),
    'wood_floor_deck': ('diff', [1.8, 1.8], False, 'Dimitrios Savva'),
    'fabric_pattern_07': ('col_1', [0.4, 0.4], False, 'Rob Tuytel'),
    # V11 exterior / site sets
    'asphalt_02': ('diff', [3.0, 3.0], False, 'Rob Tuytel'),
    'rectangular_paving': ('diff', [2.0, 2.0], False, 'Dimitrios Savva'),
    'concrete_pavement': ('diff', [1.8, 1.8], False, 'Charlotte Baglioni'),
    'painted_plaster_wall': ('diff', [2.0, 2.0], True, 'Amal Kumar'),
    'palm_tree_bark': ('diff', [1.3, 1.3], False, 'Dimitrios Savva, Rico Cilliers'),
    'sandstone_blocks_08': ('diff', [3.0, 3.0], False, 'Rob Tuytel'),
}
s2l = lambda c: np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)
l2s = lambda c: np.where(c <= 0.0031308, c * 12.92, 1.055 * np.clip(c, 0, None) ** (1 / 2.4) - 0.055)

os.makedirs(OUT, exist_ok=True)
meta = {}
for name, (stem, size, tint, author) in SETS.items():
    d = np.asarray(Image.open(f'{SRC}/{name}_{stem}_1k.jpg').convert('RGB'), dtype=np.float32) / 255
    lin = s2l(d)
    if tint:
        lum = lin @ np.array([0.2126, 0.7152, 0.0722], dtype=np.float32)
        lum = lum * (0.6 / lum.mean())
        lin = np.repeat(lum[..., None], 3, axis=2)
    avg = l2s(lin.reshape(-1, 3).mean(0))
    Image.fromarray((np.clip(l2s(lin), 0, 1) * 255 + 0.5).astype(np.uint8)).save(f'{OUT}/{name}_d.jpg', quality=86, optimize=True)
    Image.open(f'{SRC}/{name}_nor_gl_1k.jpg').convert('RGB').save(f'{OUT}/{name}_n.jpg', quality=90, optimize=True)
    r = Image.open(f'{SRC}/{name}_rough_1k.jpg').convert('L'); r.save(f'{OUT}/{name}_r.jpg', quality=85, optimize=True)
    meta[name] = {'cover': size, 'tint': tint, 'avg': '#%02x%02x%02x' % tuple(int(np.clip(v, 0, 1) * 255 + 0.5) for v in avg), 'rough': round(float(np.asarray(r).mean()) / 255, 3), 'author': author}
    print(name, meta[name])

ts = ['// GENERATED by tools/process_textures.py — CC0 photo-scanned PBR sets from polyhaven.com (see ASSET_LICENSE_LEDGER.csv).',
      'export interface PhotoSet { cover: [number, number]; tint: boolean; avg: string; rough: number; author: string }',
      'export const PHOTO_SETS: Record<string, PhotoSet> = ' + json.dumps(meta, indent=2) + ';', '']
open('src/engine/photosets.ts', 'w', encoding='utf-8').write('\n'.join(ts))
tot = sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT))
print('public/textures total MB', round(tot / 1e6, 2))
