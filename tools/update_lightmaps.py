"""Rewrite the generated reference block in src/engine/lightmaps.ts from public/lightmaps/<cat>.json (run after every bake)."""
import json, re
p = 'src/engine/lightmaps.ts'; s = open(p, encoding='utf-8').read()
rows = []
for cat in ['residential', 'ground', 'wellness', 'dining']:
    d = json.load(open(f'public/lightmaps/{cat}.json'))
    rows.append(f"  {cat}: scaled('{cat}', {d['skyRef']!r}, {d['lampRef']!r}, {d['sunRef']!r}),")
block = "export const LIGHTMAPS: Record<string, LightmapMeta> = {\n  // GENERATED by tools/update_lightmaps.py from public/lightmaps/*.json\n" + "\n".join(rows) + "\n};\n"
s = re.sub(r"export const LIGHTMAPS: Record<string, LightmapMeta> = \{.*?\n\};\n", block, s, flags=re.S)
open(p, 'w', encoding='utf-8').write(s); print(block)
